#!/usr/bin/env node
// Generate Codex custom-agent TOML from Claude agent markdown without
// changing the Claude agent source.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = resolve(__dirname, "..");
const mode = process.argv.includes("--check") ? "check" : "sync";
const AGENTS = [
  {
    source: join(REPO_ROOT, "packages", "architect", "agents", "agent.md"),
    target: join(REPO_ROOT, ".codex", "agents", "wr-architect.toml"),
    name: "wr-architect",
    fallbackDescription: "Architecture reviewer for structural and technology decisions.",
  },
  {
    source: join(REPO_ROOT, "packages", "risk-scorer", "agents", "policy.md"),
    target: join(REPO_ROOT, ".codex", "agents", "wr-risk-scorer-policy.toml"),
    name: "wr-risk-scorer-policy",
    fallbackDescription: "Validates RISK-POLICY.md drafts for ISO 31000 compliance.",
  },
];

function splitFrontmatter(markdown) {
  if (!markdown.startsWith("---\n")) {
    return { frontmatter: "", body: markdown };
  }
  const end = markdown.indexOf("\n---\n", 4);
  if (end === -1) {
    return { frontmatter: "", body: markdown };
  }
  return {
    frontmatter: markdown.slice(4, end),
    body: markdown.slice(end + "\n---\n".length),
  };
}

function frontmatterValue(frontmatter, key) {
  const lines = frontmatter.split(/\r?\n/);
  const start = lines.findIndex((line) => line.startsWith(`${key}:`));
  if (start === -1) return "";
  const values = [lines[start].slice(key.length + 1).trim()];
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^[A-Za-z0-9_-]+:/.test(lines[i])) break;
    if (/^\s+/.test(lines[i])) values.push(lines[i].trim());
  }
  return values.filter(Boolean).join(" ");
}

function tomlMultiline(value) {
  return value.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"').trimEnd();
}

function buildAgent(agent) {
  const source = readFileSync(agent.source, "utf8");
  const { frontmatter, body } = splitFrontmatter(source);
  const description =
    frontmatterValue(frontmatter, "description") ||
    agent.fallbackDescription;

  return [
    `# Generated by scripts/sync-codex-agents.mjs from ${agent.source.slice(REPO_ROOT.length + 1)}.`,
    "# Do not edit by hand; update the Claude agent markdown and re-run npm run sync:codex-agents.",
    `name = ${JSON.stringify(agent.name)}`,
    `description = ${JSON.stringify(description)}`,
    'sandbox_mode = "read-only"',
    'developer_instructions = """',
    tomlMultiline(body),
    '"""',
    "",
  ].join("\n");
}

let diverged = false;

if (mode === "check") {
  for (const agent of AGENTS) {
    const expected = buildAgent(agent);
    const current = existsSync(agent.target) ? readFileSync(agent.target, "utf8") : "";
    if (current !== expected) {
      console.error(`DIVERGED: ${agent.target.slice(REPO_ROOT.length + 1)} is out of sync`);
      diverged = true;
    }
  }
  if (diverged) {
    console.error("Run: npm run sync:codex-agents");
    process.exit(1);
  }
  console.log("OK: Codex agent TOML files match their Claude agent markdown");
  process.exit(0);
}

for (const agent of AGENTS) {
  const expected = buildAgent(agent);
  const current = existsSync(agent.target) ? readFileSync(agent.target, "utf8") : "";
  const relativeTarget = agent.target.slice(REPO_ROOT.length + 1);
  mkdirSync(dirname(agent.target), { recursive: true });
  if (current === expected) {
    console.log(`OK: ${relativeTarget} already in sync`);
  } else {
    writeFileSync(agent.target, expected, "utf8");
    console.log(`synced: ${relativeTarget}`);
  }
}
