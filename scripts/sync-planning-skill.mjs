#!/usr/bin/env node
// Keep the independently usable ITIL compatibility entrypoint in sync.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

function directorySnapshot(directory) {
  if (!existsSync(directory)) return null;
  return JSON.stringify(readdirSync(directory, { recursive: true }).sort()
    .filter(name => statSync(join(directory, name)).isFile())
    .map(name => [name, readFileSync(join(directory, name), 'base64')]));
}
for (const name of ['outcome-led-planning', 'setup-github-tracking']) {
  const canonical = new URL(`../packages/planning/skills/${name}/SKILL.md`, import.meta.url);
  const compatibility = new URL(`../packages/itil/skills/${name}/SKILL.md`, import.meta.url);
  const directories = name === 'setup-github-tracking' ? ['references/', 'scripts/', 'agents/'] : ['references/', 'scripts/'];
  const source = readFileSync(canonical, 'utf8');
  const identity = `name: ${name}\n`;
  if (!source.startsWith(`---\n${identity}`)) throw new Error(`Unexpected canonical ${name} skill identity`);
  const expected = source.replace(identity, `# Generated by scripts/sync-planning-skill.mjs; edit packages/planning instead.\nname: wr-itil:${name}\n`);
  if (process.argv.includes('--check')) {
    if (!existsSync(compatibility) || readFileSync(compatibility, 'utf8') !== expected ||
        directories.some(directory => directorySnapshot(fileURLToPath(new URL(directory, compatibility))) !== directorySnapshot(fileURLToPath(new URL(directory, canonical))))) {
      console.error('Planning compatibility skill drift: run npm run sync:planning-skill');
      process.exit(1);
    }
    console.log('Planning compatibility skill is in sync.');
  } else {
    mkdirSync(new URL('./', compatibility), { recursive: true });
    for (const directory of directories) {
      const sourceDirectory = fileURLToPath(new URL(directory, canonical));
      const targetDirectory = fileURLToPath(new URL(directory, compatibility));
      rmSync(targetDirectory, { recursive: true, force: true });
      if (existsSync(sourceDirectory)) cpSync(sourceDirectory, targetDirectory, { recursive: true });
    }
    writeFileSync(compatibility, expected);
    console.log(`Synced ${fileURLToPath(compatibility)}.`);
  }

}
