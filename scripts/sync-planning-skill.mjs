#!/usr/bin/env node
// Keep the independently usable ITIL compatibility entrypoint in sync.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const canonical = new URL('../packages/planning/skills/outcome-led-planning/SKILL.md', import.meta.url);
const compatibility = new URL('../packages/itil/skills/outcome-led-planning/SKILL.md', import.meta.url);
const source = readFileSync(canonical, 'utf8');
if (!/^---\nname: outcome-led-planning\n/.test(source)) throw new Error('Unexpected canonical planning skill identity');
const expected = source.replace('name: outcome-led-planning\n', '# Generated by scripts/sync-planning-skill.mjs; edit packages/planning instead.\nname: wr-itil:outcome-led-planning\n');
if (process.argv.includes('--check')) {
  if (readFileSync(compatibility, 'utf8') !== expected) {
    console.error('Planning compatibility skill drift: run npm run sync:planning-skill');
    process.exit(1);
  }
  console.log('Planning compatibility skill is in sync.');
} else {
  writeFileSync(compatibility, expected);
  console.log(`Synced ${fileURLToPath(compatibility)}.`);
}
